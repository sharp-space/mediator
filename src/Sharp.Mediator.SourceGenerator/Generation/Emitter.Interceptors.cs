using System;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace Sharp.Mediator.SourceGenerator.Generation;

internal enum InterceptedKind
{
    VoidRequest,
    Request,
    InferredRequest,
    Event,
    Stream,
    InferredStream
}

/// <summary>How an interceptor finds out that a message is exactly its static type before using that type's chain.</summary>
internal enum InterceptedLookup
{
    /// <summary>It checks the runtime type on every call.</summary>
    Checked,

    /// <summary>It needs no check: nothing can derive from a value type, nor from a sealed class compiled here.</summary>
    Exact,

    /// <summary>
    /// It needs none while the type is sealed, which it reads when the interceptors load: a class of another assembly can be unsealed without this
    /// one being recompiled.
    /// </summary>
    ExactIfSealed,

    /// <summary>
    /// It names no type, since generated code cannot write the call's types: a type parameter, a private type, or a type only an extern alias reaches. A
    /// generic interceptor takes the call's type arguments as its own.
    /// </summary>
    Unnamed
}

/// <summary>A statically-typed mediator call site that can bypass the generic virtual call.</summary>
internal readonly record struct InterceptedCall(
    int Version,
    string Data,
    InterceptedKind Kind,
    string MessageFullyQualifiedName,
    string? ResponseFullyQualifiedName,
    InterceptedLookup Lookup
);

internal static partial class Emitter
{
    internal const string InterceptorsNamespace = "Sharp.Mediator.Generated.Interceptors";

    private const string UnnamedKey = "UnnamedKey";

    public static void EmitInterceptors(SourceProductionContext context, ImmutableArray<InterceptedCall> calls)
    {
        if (calls.IsEmpty) return;

        var stringBuilder = new StringBuilder();
        stringBuilder.AppendLine("// <auto-generated/>");

        // Oblivious on purpose: a response such as `User?` prints without its annotation, which enabled nullable
        // context would report as a signature mismatch with the intercepted call.
        stringBuilder.AppendLine("#nullable disable");

        // Every code, not a list: a message can be [Obsolete] or [Experimental] under any diagnostic id, and the call
        // site that uses it has already dealt with that.
        stringBuilder.AppendLine("#pragma warning disable");
        stringBuilder.AppendLine("namespace System.Runtime.CompilerServices");
        stringBuilder.AppendLine("{");
        stringBuilder.AppendLine("    [global::System.AttributeUsage(global::System.AttributeTargets.Method, AllowMultiple = true)]");
        stringBuilder.AppendLine("    file sealed class InterceptsLocationAttribute : global::System.Attribute");
        stringBuilder.AppendLine("    {");
        stringBuilder.AppendLine("        public InterceptsLocationAttribute(int version, string data) { }");
        stringBuilder.AppendLine("    }");
        stringBuilder.AppendLine("}");
        stringBuilder.AppendLine();
        stringBuilder.AppendLine($"namespace {InterceptorsNamespace}");
        stringBuilder.AppendLine("{");
        AppendGeneratedCodeAttributes(stringBuilder, "    ");
        stringBuilder.AppendLine("    [global::System.Diagnostics.StackTraceHidden]");
        stringBuilder.AppendLine("    file static class MediatorInterceptors");
        stringBuilder.AppendLine("    {");

        // Static readonly, so the JIT folds each flag into the interceptors that read it once this class has loaded.
        // Where dynamic code is not supported, as under Native AOT, the interceptors read no flag and take the checked
        // lookup: the compiler cannot run the static constructor ahead of time, so each read would check that it has
        // run, while the checked lookup costs nothing there, since that compiler sees every type that derives from the
        // message and folds the check away for one that none does.
        var sealedFlags = calls
            .Where(static x => x.Lookup == InterceptedLookup.ExactIfSealed)
            .Select(static x => x.MessageFullyQualifiedName)
            .Distinct()
            .OrderBy(static x => x, StringComparer.Ordinal)
            .Select(static (message, flag) => (message, Name: $"Sealed{flag}"))
            .ToDictionary(static x => x.message, static x => x.Name);

        foreach (var flag in sealedFlags.OrderBy(static x => x.Value, StringComparer.Ordinal))
            stringBuilder.AppendLine($"        private static readonly bool {flag.Value} = typeof({flag.Key}).IsSealed;");

        if (sealedFlags.Count > 0) stringBuilder.AppendLine();

        // A struct per message, which every interceptor of the message passes to MediatorCalls as its key.
        var keys = calls
            .Where(static x => x.Lookup != InterceptedLookup.Unnamed)
            .Select(static x => x.MessageFullyQualifiedName)
            .Distinct()
            .OrderBy(static x => x, StringComparer.Ordinal)
            .Select(static (message, key) => (message, Name: $"Key{key}"))
            .ToDictionary(static x => x.message, static x => x.Name);

        foreach (var key in keys.OrderBy(static x => x.Value, StringComparer.Ordinal))
            stringBuilder.AppendLine($"        private struct {key.Value} {{ }}");

        // The key of every call whose message type generated code cannot write, which share one instance as calls
        // through the interface do. An inferred one needs none, as it takes the route that finds the runtime type.
        var unnamedKeyed = calls.Any(static x => x is
        {
            Lookup: InterceptedLookup.Unnamed,
            Kind: not InterceptedKind.InferredRequest and not InterceptedKind.InferredStream
        });

        if (unnamedKeyed) stringBuilder.AppendLine($"        private struct {UnnamedKey} {{ }}");
        if (keys.Count > 0 || unnamedKeyed) stringBuilder.AppendLine();

        var index = 0;
        foreach (var group in calls
                     .GroupBy(static x => (x.Kind, x.MessageFullyQualifiedName, x.ResponseFullyQualifiedName, x.Lookup))
                     .OrderBy(static x => x.Key.MessageFullyQualifiedName, StringComparer.Ordinal)
                     .ThenBy(static x => x.Key.Kind))
        {
            foreach (var call in group.OrderBy(static x => x.Data, StringComparer.Ordinal))
                stringBuilder.AppendLine($"        [global::System.Runtime.CompilerServices.InterceptsLocation({call.Version}, \"{call.Data}\")]");

            stringBuilder.AppendLine(
                "        [global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]");

            AppendInterceptor(
                stringBuilder, group.Key.Kind, group.Key.MessageFullyQualifiedName, group.Key.ResponseFullyQualifiedName,
                group.Key.Lookup, sealedFlags.TryGetValue(group.Key.MessageFullyQualifiedName, out var flag) ? flag : null,
                group.Key.Lookup == InterceptedLookup.Unnamed ? UnnamedKey : keys[group.Key.MessageFullyQualifiedName],
                index++);
        }

        stringBuilder.AppendLine("    }");
        stringBuilder.AppendLine("}");
        context.AddSource("SharpMediator.Interceptors.g.cs", SourceText.From(stringBuilder.ToString(), Encoding.UTF8));
    }

    // Every interceptor makes one call into MediatorCalls with its message's key, so what the call does is the
    // library's, and still an instance of that message's own. It passes whether the message is exactly its static type:
    // yes for a type nothing can derive from, no for one that something can, and for a class of another assembly,
    // whether it is sealed.
    private static void AppendInterceptor(
        StringBuilder stringBuilder,
        InterceptedKind kind,
        string message,
        string? response,
        InterceptedLookup lookup,
        string? sealedFlag,
        string key,
        int index
    )
    {
        const string requester = "this global::Sharp.Mediator.IRequester requester";
        const string publisher = "this global::Sharp.Mediator.IPublisher publisher";
        const string token = "global::System.Threading.CancellationToken cancellationToken = default";
        const string target = "global::Sharp.Mediator.Bindings.MediatorCalls";
        const string task = "global::System.Threading.Tasks.ValueTask";
        const string stream = "global::System.Collections.Generic.IAsyncEnumerable";

        // A call whose types generated code cannot write, such as one from generic code, gets a generic interceptor of
        // the intercepted method's own type parameters and constraints. What it saves is the generic virtual call,
        // which looks its target up on every call. An inferred one names no message type for the key to stand for, so
        // it takes the route that dispatches on the runtime type.
        if (lookup == InterceptedLookup.Unnamed)
        {
            var (typeParameters, receiver, messageType, returnType, constraint, forward) = kind switch
            {
                InterceptedKind.VoidRequest => (
                    "<TRequest>", requester, "TRequest", task, " where TRequest : global::Sharp.Mediator.IRequest",
                    $"Request<TRequest, {key}>(requester, message, false, cancellationToken)"),
                InterceptedKind.Request => (
                    "<TRequest, TResponse>", requester, "TRequest", $"{task}<TResponse>",
                    " where TRequest : global::Sharp.Mediator.IRequest<TResponse>",
                    $"Request<TRequest, TResponse, {key}>(requester, message, false, cancellationToken)"),
                InterceptedKind.InferredRequest => (
                    "<TResponse>", requester, "global::Sharp.Mediator.IRequest<TResponse>", $"{task}<TResponse>", "",
                    "InferredRequest<TResponse>(requester, message, cancellationToken)"),
                InterceptedKind.Stream => (
                    "<TRequest, TResponse>", requester, "TRequest", $"{stream}<TResponse>",
                    " where TRequest : global::Sharp.Mediator.IStreamRequest<TResponse>",
                    $"RequestStream<TRequest, TResponse, {key}>(requester, message, false, cancellationToken)"),
                InterceptedKind.InferredStream => (
                    "<TResponse>", requester, "global::Sharp.Mediator.IStreamRequest<TResponse>", $"{stream}<TResponse>", "",
                    "InferredRequestStream<TResponse>(requester, message, cancellationToken)"),
                _ => (
                    "<TEvent>", publisher, "TEvent", task, " where TEvent : global::Sharp.Mediator.IEvent",
                    $"Publish<TEvent, {key}>(publisher, message, false, cancellationToken)")
            };

            stringBuilder.AppendLine(
                $"        public static {returnType} Call{index}{typeParameters}({receiver}, {messageType} message, {token}){constraint} =>");

            stringBuilder.AppendLine($"            {target}.{forward};");

            return;
        }

        var exact = lookup switch
        {
            InterceptedLookup.Exact => "true",
            InterceptedLookup.ExactIfSealed =>
                $"global::System.Runtime.CompilerServices.RuntimeFeature.IsDynamicCodeSupported && {sealedFlag}",
            _ => "false"
        };

        var (namedReceiver, returns, parameter, call) = kind switch
        {
            InterceptedKind.VoidRequest => (requester, task, message, $"Request<{message}, {key}>(requester"),
            InterceptedKind.Request =>
                (requester, $"{task}<{response}>", message, $"Request<{message}, {response}, {key}>(requester"),
            InterceptedKind.InferredRequest => (
                requester, $"{task}<{response}>", $"global::Sharp.Mediator.IRequest<{response}>",
                $"InferredRequest<{message}, {response}, {key}>(requester"),
            InterceptedKind.Stream =>
                (requester, $"{stream}<{response}>", message, $"RequestStream<{message}, {response}, {key}>(requester"),
            InterceptedKind.InferredStream => (
                requester, $"{stream}<{response}>", $"global::Sharp.Mediator.IStreamRequest<{response}>",
                $"InferredRequestStream<{message}, {response}, {key}>(requester"),
            _ => (publisher, task, message, $"Publish<{message}, {key}>(publisher")
        };

        stringBuilder.AppendLine(
            $"        public static {returns} Call{index}({namedReceiver}, {parameter} message, {token}) =>");

        stringBuilder.AppendLine($"            {target}.{call}, message, {exact}, cancellationToken);");
    }
}