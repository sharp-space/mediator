using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Globalization;
using System.Linq;
using System.Reflection;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;
using Sharp.Mediator.SourceGenerator.Analysis;

namespace Sharp.Mediator.SourceGenerator.Generation;

/// <summary>Emits the generated DI registrars and message slot assignments into the consumer assembly.</summary>
internal static partial class Emitter
{
    private const string ToolName = "Sharp.Mediator.SourceGenerator";

    // Keys of the assembly metadata generated code records for the generator of an assembly that references this one,
    // which reads it at build time (see ReferenceAnalysis): the contract the code was generated for, and the middleware
    // its closer closes over the assembly's own messages. Assembly metadata, so the records add no public type to
    // Sharp.Mediator.Bindings and, being strings, keep no type alive, though a trimmed build carries them. Each key
    // appears once, every middleware in one value, since code that reads an assembly's metadata into a dictionary by
    // key throws on a key that repeats.
    private const string ContractKey = "Sharp.Mediator.Contract";
    internal const string ClosedMiddlewareKey = "Sharp.Mediator.ClosedMiddleware";

    /// <summary>Separates the middleware in the value of <see cref="ClosedMiddlewareKey" />; no type name holds it.</summary>
    internal const char ClosedMiddlewareSeparator = ';';

    // Sharp-family diagnostic allocation: SMDxxx belongs to Mediator; 001-009 is message/dispatch and 010-019 is
    // middleware. Keep new IDs inside their feature band and never renumber or reuse an ID after it ships. When a
    // feature band is full, the feature continues in the product's next unassigned ten-number band, and that band is
    // added to the band list.

    // [GeneratedCode]'s version comes from <Version> in Directory.Build.props — the SDK bakes it into this generator
    // assembly's AssemblyInformationalVersion, which we read here instead of hardcoding a literal. Resolved once
    // (constant per build); we trim the "+<sha>" build-metadata suffix and fall back to the assembly version.
    private static readonly string ToolVersion = ResolveToolVersion(typeof(Emitter).Assembly);

    internal static string ResolveToolVersion(Assembly assembly)
    {
        var informational = assembly
            .GetCustomAttribute<AssemblyInformationalVersionAttribute>()?.InformationalVersion;

        return NormalizeToolVersion(informational, assembly.GetName().Version);
    }

    internal static string NormalizeToolVersion(string? informational, Version? assemblyVersion)
    {
        if (informational is { Length: > 0 })
        {
            var plus = informational.IndexOf('+');
            return plus < 0 ? informational : informational.Substring(0, plus);
        }

        return assemblyVersion?.ToString() ?? "1.0.0.0";
    }

    // Stamps the standard generated-code attributes on a type: [GeneratedCode] attributes it to this tool,
    // [ExcludeFromCodeCoverage] keeps the module-initializer scaffolding out of coverage, and [DebuggerNonUserCode]
    // makes the debugger step over it. [Obsolete] makes the type an obsolete context: a message marked [Obsolete(...,
    // error: true)] is an error wherever else it is named, and no pragma suppresses an error. Code that names the
    // message in source still reports it there.
    internal static void AppendGeneratedCodeAttributes(StringBuilder builder, string indent)
    {
        builder.AppendLine($"{indent}[global::System.CodeDom.Compiler.GeneratedCode(\"{ToolName}\", \"{ToolVersion}\")]");
        builder.AppendLine($"{indent}[global::System.Diagnostics.CodeAnalysis.ExcludeFromCodeCoverage]");
        builder.AppendLine($"{indent}[global::System.Diagnostics.DebuggerNonUserCode]");
        builder.AppendLine($"{indent}[global::System.Obsolete(\"Generated by {ToolName}. Not for direct use.\")]");
    }

    public static void Emit(
        SourceProductionContext context,
        ImmutableArray<HandlerInfo> handlers,
        ImmutableArray<MiddlewareInfo> middlewares,
        ImmutableArray<ClosingTarget> referencedMessages,
        string assemblyIdentifier,
        bool consumesRuntime,
        EquatableArray<string> varianceSatisfied,
        LanguageVersion languageVersion
    )
    {
        // Generated code runs a module initializer, which needs C# 9, and opens with #nullable, which needs C# 8. An
        // older version gets no generated code and one error that names the setting, rather than errors inside
        // generated files that do not.
        if (languageVersion < LanguageVersion.CSharp9)
        {
            if (consumesRuntime)
            {
                context.ReportDiagnostic(Diagnostic.Create(
                    DiagnosticDescriptors.LanguageVersionTooOld, Location.None, languageVersion.ToDisplayString()));
            }

            return;
        }

        var (middlewareList, excludedMessages) = HandlerAnalysis.Analyze(static (_, _, _) => { }, handlers, middlewares);

        // A message with a handler here is closed over as one of this compilation's own.
        var localMessages = new HashSet<string>(handlers.Select(static x => x.MessageFullyQualifiedName), StringComparer.Ordinal);
        var referenced = referencedMessages.Where(x => !localMessages.Contains(x.Handler.MessageFullyQualifiedName)).ToList();

        // Nothing to dispatch or close: the assembly contributes no mediator registrar, only the handler
        // registrar that tells AddHandlers the generator ran, so an assembly without handlers is not mistaken for
        // one without it. An assembly without handlers still closes the middleware it sees over the messages of
        // the assemblies it references.
        if (handlers.IsEmpty && (!consumesRuntime || middlewareList.Count == 0 || referenced.Count == 0))
        {
            if (consumesRuntime)
            {
                var marker = NewCompilationUnit(assemblyIdentifier);
                EmitHandlerRegistrar(marker, []);
                marker.AppendLine("}");
                context.AddSource("SharpMediator.Registrations.g.cs", SourceText.From(marker.ToString(), Encoding.UTF8));
            }

            return;
        }

        bool IsEmittable(HandlerInfo handler) => !excludedMessages.Contains(handler.MessageFullyQualifiedName);

        var requests = handlers
            .Where(static x => x.Kind is MessageKind.VoidRequest or MessageKind.Request)
            .Where(IsEmittable)
            .GroupBy(static x => x.MessageFullyQualifiedName)
            .Select(static x => x.First())
            .OrderBy(static x => x.MessageFullyQualifiedName, StringComparer.Ordinal)
            .ToList();

        var events = handlers
            .Where(static x => x.Kind == MessageKind.Event)
            .Where(IsEmittable)
            .GroupBy(static x => x.MessageFullyQualifiedName)
            .Select(static x => x.First())
            .OrderBy(static x => x.MessageFullyQualifiedName, StringComparer.Ordinal)
            .ToList();

        var streams = handlers
            .Where(static x => x.Kind == MessageKind.Stream)
            .Where(IsEmittable)
            .GroupBy(static x => x.MessageFullyQualifiedName)
            .Select(static x => x.First())
            .OrderBy(static x => x.MessageFullyQualifiedName, StringComparer.Ordinal)
            .ToList();

        var voidRequests = requests.Where(static x => x.Kind == MessageKind.VoidRequest).ToList();
        var responseRequests = requests.Where(static x => x.Kind == MessageKind.Request).ToList();

        var registrar = NewCompilationUnit(assemblyIdentifier, middlewareList);
        EmitRegistrar(
            registrar, voidRequests, responseRequests, events, streams, referenced, middlewareList,
            new HashSet<string>(varianceSatisfied, StringComparer.Ordinal));

        registrar.AppendLine();

        EmitHandlerRegistrar(registrar, [.. handlers.Where(IsEmittable)]);
        registrar.AppendLine("}");
        context.AddSource("SharpMediator.Registrations.g.cs", SourceText.From(registrar.ToString(), Encoding.UTF8));
    }

    /// <summary>One middleware in the value of <see cref="ClosedMiddlewareKey" />.</summary>
    internal static string ClosedMiddlewareRecord(string assembly, string middleware) => $"{assembly}|{middleware}";

    private static StringBuilder NewCompilationUnit(string assemblyIdentifier, List<MiddlewareInfo>? closedMiddleware = null)
    {
        var stringBuilder = new StringBuilder();
        AppendFileHeader(stringBuilder);
        AppendMetadata(stringBuilder, ContractKey, Contract.ToString(CultureInfo.InvariantCulture));
        var records = (closedMiddleware ?? [])
            .Select(static x => ClosedMiddlewareRecord(x.AssemblyName, x.MatchTypeFullyQualifiedName))
            .Distinct()
            .OrderBy(static x => x, StringComparer.Ordinal)
            .ToList();

        if (records.Count > 0)
            AppendMetadata(stringBuilder, ClosedMiddlewareKey, string.Join(ClosedMiddlewareSeparator.ToString(), records));

        stringBuilder.AppendLine($"namespace Sharp.Mediator.Generated.{assemblyIdentifier}");
        stringBuilder.AppendLine("{");
        return stringBuilder;
    }

    private static void AppendMetadata(StringBuilder stringBuilder, string key, string value) =>
        stringBuilder.AppendLine(
            $"[assembly: global::System.Reflection.AssemblyMetadata({SymbolDisplay.FormatLiteral(key, true)}, " +
            $"{SymbolDisplay.FormatLiteral(value, true)})]");

    // The constraint probe opens with these lines too, so the compiler judges a pair in the context it compiles the
    // generated code in.
    internal static void AppendFileHeader(StringBuilder stringBuilder)
    {
        stringBuilder.AppendLine("// <auto-generated/>");

        // Annotations only: type names are rendered without nullable modifiers, so `IRequest<User?>` closes over plain
        // `User`. Nullable warnings on that erased form would be noise that breaks TreatWarningsAsErrors.
        stringBuilder.AppendLine("#nullable enable annotations");

        // Every code, not a list: a message can be [Obsolete] or [Experimental] under any diagnostic id, and the code
        // that declares it has already dealt with that.
        stringBuilder.AppendLine("#pragma warning disable");
    }
}